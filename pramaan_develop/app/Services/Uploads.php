<?php
declare(strict_types=1);

namespace App\Services;

use App\Models\Attachment;
use finfo;

/**
 * Attachments: PDF / JPG / JPEG / PNG, max 5 MB each, max 10 files.
 * Type is checked by extension AND by the file's real content (magic bytes);
 * files are saved under storage/uploads with a random name, never in the web root.
 */
final class Uploads
{
    public const MAX_SIZE = 5 * 1024 * 1024;
    public const MAX_FILES = 10;
    private const ALLOWED = ['pdf' => 'application/pdf', 'jpg' => 'image/jpeg', 'jpeg' => 'image/jpeg', 'png' => 'image/png'];

    public static function dir(): string
    {
        return BASE_PATH . '/storage/uploads';
    }

    /** @return array|string validated files, or an error message */
    public static function check(array $files): array|string
    {
        if (count($files) > self::MAX_FILES) {
            return 'You can attach at most ' . self::MAX_FILES . ' files.';
        }
        $out = [];
        $names = [];
        $fi = new finfo(FILEINFO_MIME_TYPE);
        foreach ($files as $f) {
            $name = self::cleanName($f['name']);
            if ($f['error'] !== UPLOAD_ERR_OK || !is_uploaded_file($f['tmp'])) {
                return '"' . $name . '" could not be uploaded' . ($f['error'] === UPLOAD_ERR_INI_SIZE || $f['error'] === UPLOAD_ERR_FORM_SIZE ? ' — the limit is 5 MB.' : '.');
            }
            $ext = strtolower(pathinfo($name, PATHINFO_EXTENSION));
            if (!isset(self::ALLOWED[$ext])) {
                return '"' . $name . '": only PDF, JPG, JPEG or PNG files are allowed.';
            }
            $size = (int) filesize($f['tmp']);
            if ($size <= 0) {
                return '"' . $name . '" is empty.';
            }
            if ($size > self::MAX_SIZE) {
                return '"' . $name . '" is larger than 5 MB.';
            }
            $mime = (string) $fi->file($f['tmp']);
            if ($mime !== self::ALLOWED[$ext] || !self::magicOk($f['tmp'], $mime)) {
                return '"' . $name . '": file content does not match its extension.';
            }
            $k = mb_strtolower($name);
            if (isset($names[$k])) {
                return '"' . $name . '" is already added (a file with the same name).';
            }
            $names[$k] = true;
            $out[] = ['name' => $name, 'tmp' => $f['tmp'], 'size' => $size, 'mime' => $mime, 'ext' => $ext === 'jpeg' ? 'jpg' : $ext];
        }
        return $out;
    }

    /** Move one checked file into storage and add its row. */
    public static function store(array $f, array $ctx): array
    {
        $sub = date('Y/m');
        $dir = self::dir() . '/' . $sub;
        if (!is_dir($dir)) {
            mkdir($dir, 0700, true);
        }
        $stored = $sub . '/' . bin2hex(random_bytes(16)) . '.' . $f['ext'];
        $path = self::dir() . '/' . $stored;
        if (!move_uploaded_file($f['tmp'], $path)) {
            throw new \RuntimeException('Could not save the uploaded file.');
        }
        @chmod($path, 0600);
        $id = Attachment::insert([
            'task_id' => $ctx['task_id'] ?? null, 'round_id' => $ctx['round_id'] ?? null, 'property_id' => $ctx['property_id'],
            'context' => $ctx['context'] ?? 'TASK_RESPONSE', 'file_name' => $f['name'], 'stored_name' => $stored, 'mime' => $f['mime'],
            'size' => $f['size'], 'sha256' => hash_file('sha256', $path), 'uploaded_by' => $ctx['by'],
        ]);
        return ['attachment_id' => $id, 'file_name' => $f['name'], 'path' => $path];
    }

    /** Save bytes generated by the seeder (sample PDF / JPEG). */
    public static function storeBytes(string $bytes, string $name, string $mime, array $ctx): int
    {
        $sub = date('Y/m');
        $dir = self::dir() . '/' . $sub;
        if (!is_dir($dir)) {
            mkdir($dir, 0700, true);
        }
        $stored = $sub . '/' . bin2hex(random_bytes(16)) . '.' . ($mime === 'application/pdf' ? 'pdf' : 'jpg');
        file_put_contents(self::dir() . '/' . $stored, $bytes);
        return Attachment::insert([
            'task_id' => $ctx['task_id'] ?? null, 'round_id' => $ctx['round_id'] ?? null, 'property_id' => $ctx['property_id'],
            'context' => 'TASK_RESPONSE', 'file_name' => $name, 'stored_name' => $stored, 'mime' => $mime, 'size' => strlen($bytes),
            'sha256' => hash('sha256', $bytes), 'uploaded_by' => $ctx['by'], 'created_at' => $ctx['at'] ?? now(),
        ]);
    }

    public static function discard(array $paths): void
    {
        foreach ($paths as $p) {
            if (is_file($p)) {
                @unlink($p);
            }
        }
    }

    public static function path(array $attachment): ?string
    {
        $stored = (string) $attachment['stored_name'];
        if (!preg_match('~^\d{4}/\d{2}/[a-f0-9]{32}\.(pdf|jpg|png)$~', $stored)) {
            return null;
        }
        $p = self::dir() . '/' . $stored;
        return is_file($p) ? $p : null;
    }

    private static function cleanName(string $name): string
    {
        $name = basename(str_replace('\\', '/', $name));
        $name = preg_replace('/[^\p{L}\p{N} ._()-]/u', '_', $name) ?? 'file';
        $name = trim($name, ' .');
        return mb_substr($name !== '' ? $name : 'file', 0, 150);
    }

    private static function magicOk(string $file, string $mime): bool
    {
        $h = (string) file_get_contents($file, false, null, 0, 8);
        return match ($mime) {
            'application/pdf' => str_starts_with($h, '%PDF-'),
            'image/jpeg'      => str_starts_with($h, "\xFF\xD8\xFF"),
            'image/png'       => str_starts_with($h, "\x89PNG\r\n\x1A\n"),
            default           => false,
        };
    }
}
